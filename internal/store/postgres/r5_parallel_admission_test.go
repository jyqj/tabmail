func TestR5PGAdmissionBoundedAndReusable(t *testing.T) {
	a := newR5PGAdmission()
	releases := []func(){a.acquire(), a.acquire(), a.acquire(), a.acquire()}
	if len(a.slots) != 4 || cap(a.slots) != 4 {
		t.Fatal("admission is not exactly four lanes")
	}
	select {
	case a.slots <- struct{}{}:
		t.Fatal("fifth lane admitted")
	default:
	}
	releases[0]()
	releases[0]()
	if len(a.slots) != 3 {
		t.Fatal("duplicate release consumed another owner's permit")
	}
	replacement := a.acquire()
	if len(a.slots) != 4 {
		t.Fatal("released lane could not be reused")
	}
	for _, release := range releases[1:] {
		release()
	}
	replacement()
	if len(a.slots) != 0 {
		t.Fatal("admission permits leaked")
	}
}
